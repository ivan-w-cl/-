"""Build stage/timeline-ep01.js from the voice timings and scenes.js.
Usage: python3 -I build.py   (run inside this folder after tts.py)"""
import json, math, os, datetime
here = os.path.dirname(os.path.abspath(__file__))
T = json.load(open(os.path.join(here, 'audio', 'timing.json')))
# captions: long lines are split in two at a comma / space near the middle, timed by character share
caps = []
for l in T['lines']:
    s = l['text']
    if len(s) > 70:
        mid = len(s) // 2; cands = [i for i, ch in enumerate(s[:-1]) if ch == '.' and s[i + 1] == ' '] or [i for i, ch in enumerate(s) if ch == ','] or []
        cut = min(cands, key=lambda i: abs(i - mid)) + 1 if cands and min(abs(i - mid) for i in cands) < len(s) * 0.28 else min((i for i, ch in enumerate(s) if ch == ' ' and s[i + 1:].split(' ')[0].lower() not in ('a', 'and', 'the', 'of', 'in', 'to', 'it', 'as', 'half')), key=lambda i: abs(i - mid))
        a, b = s[:cut].strip(), s[cut:].strip(); tm = l['start'] + (l['end'] - l['start']) * len(a) / (len(a) + len(b))
        caps += [{'text': a, 'start': l['start'], 'end': round(tm, 3)}, {'text': b, 'start': round(tm, 3), 'end': l['end']}]
    else: caps.append({'text': s, 'start': l['start'], 'end': l['end']})
# sunrise / sunset for Liverpool (53.41 N, 2.98 W), local clock time, standard formula with -0.833 deg horizon
def sun(day, tz):
    lat, lon = math.radians(53.41), -2.98
    n = day.timetuple().tm_yday; g = 2 * math.pi / 365 * (n - 1 + 0.5)
    eot = 229.18 * (0.000075 + 0.001868 * math.cos(g) - 0.032077 * math.sin(g) - 0.014615 * math.cos(2 * g) - 0.040849 * math.sin(2 * g))
    dec = 0.006918 - 0.399912 * math.cos(g) + 0.070257 * math.sin(g) - 0.006758 * math.cos(2 * g) + 0.000907 * math.sin(2 * g) - 0.002697 * math.cos(3 * g) + 0.00148 * math.sin(3 * g)
    ha = math.degrees(math.acos((math.cos(math.radians(90.833)) - math.sin(lat) * math.sin(dec)) / (math.cos(lat) * math.cos(dec))))
    noon = 720 - 4 * lon - eot + tz * 60
    return [round((noon - 4 * ha) / 60, 3), round((noon + 4 * ha) / 60, 3), round(90 - 53.41 + math.degrees(dec), 1)]
EP = {'duration': T['duration'], 'lines': T['lines'], 'captions': caps, 'sun': {'dec': sun(datetime.date(2026, 12, 21), 0), 'jun': sun(datetime.date(2026, 6, 21), 1)}}
print('sun dec', EP['sun']['dec'], 'len', round(EP['sun']['dec'][1] - EP['sun']['dec'][0], 2), '| jun', EP['sun']['jun'], 'len', round(EP['sun']['jun'][1] - EP['sun']['jun'][0], 2))
open(os.path.join(here, '..', '..', 'stage', 'timeline-ep01.js'), 'w').write('/* GENERATED by explainers/ep01-weather/build.py: edit scenes.js / script.json instead */\nconst EP = ' + json.dumps(EP, ensure_ascii=False) + ';\n' + open(os.path.join(here, 'scenes.js')).read())
def ts(x): ms = int(round(x * 1000)); return '%02d:%02d:%02d,%03d' % (ms // 3600000, ms // 60000 % 60, ms // 1000 % 60, ms % 1000)
open(os.path.join(here, 'audio', 'captions.srt'), 'w').write('\n'.join(f"{i+1}\n{ts(c['start'])} --> {ts(c['end'])}\n{c['text']}\n" for i, c in enumerate(caps)))
print('captions', len(caps), 'duration', T['duration'])
