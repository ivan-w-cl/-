// Measures recorded narration clips voice/<lineId>.wav (e.g. S01L1.wav) with ffprobe and writes voice-durations.js,
// so the timeline, captions and SRT follow the real voice. Then run tools/export.cjs and mix with tools/mix-voice.sh.
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
const ROOT = path.resolve(__dirname, '..'), dir = path.join(ROOT, 'voice'), out = {};
for (const f of fs.readdirSync(dir).filter(f => /^S\d\dL\d+\.(wav|mp3)$/.test(f))) {
  out[f.replace(/\.(wav|mp3)$/, '')] = +execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', path.join(dir, f)]).toString().trim();
}
fs.writeFileSync(path.join(ROOT, 'voice-durations.js'), `/* generated by tools/set-voice.cjs */\nwindow.VOICE_DURATIONS = ${JSON.stringify(out, null, 1)};\n`);
console.log(Object.keys(out).length, 'clips measured');
